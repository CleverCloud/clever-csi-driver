#!/usr/bin/env python3
"""Render Helm into Axo-style manifest.txt bundles; never touches Axo itself."""
import argparse
import difflib
from pathlib import Path
import subprocess
import yaml

ROOT = Path(__file__).resolve().parents[1]
ORDER = {"ServiceAccount": 10, "ClusterRole": 20, "ClusterRoleBinding": 21,
         "Role": 22, "RoleBinding": 23, "Deployment": 30, "DaemonSet": 40}


def render(phase, cluster_id="${OVD_CLUSTER_ID}", organisation_id="${OVD_CSI_ORGANISATION_ID}", axo_url=None, image_tag=None, image_digest=None):
    command = ["helm", "template", "clever-csi", str(ROOT / "charts/clever-csi-driver"),
               "--namespace", "kube-system"]
    if image_tag is not None:
        command += ["--set-string", f"image.tag={image_tag}"]
    if image_digest is not None:
        command += ["--set-string", f"image.digest={image_digest}"]
    if phase != "stage":
        command += ["-f", str(ROOT / f"deploy/values-{phase}.yaml"),
                    "--set-string", f"controller.clusterId={cluster_id}",
                    "--set-string", f"controller.organisationId={organisation_id}"]
        if axo_url is not None:
            command += ["--set-string", f"controller.axoUrl={axo_url}"]
    return [doc for doc in yaml.safe_load_all(subprocess.check_output(command, text=True)) if doc]


def normalize(value):
    if isinstance(value, dict):
        for key in ["helm.sh/chart", "app.kubernetes.io/managed-by"]:
            value.pop(key, None)
        for child in value.values():
            normalize(child)
    elif isinstance(value, list):
        for child in value:
            normalize(child)


def bundle(phase, **settings):
    docs = render(phase, **settings)
    for doc in docs:
        if doc.get("kind") not in ORDER:
            kind = doc.get("kind", "<missing kind>")
            name = doc.get("metadata", {}).get("name", "<missing name>")
            raise ValueError(f"unsupported plugin-owned resource {kind}/{name}; shared resources must remain externally managed")
    result = {}
    for index, doc in enumerate(sorted(docs, key=lambda d: (ORDER[d["kind"]], d["metadata"]["name"])), 1):
        normalize(doc)
        # The Axo renderer supplies app.kubernetes.io/managed-by and plugin labels.
        name = f'{index:02d}-{doc["kind"].lower()}-{doc["metadata"]["name"]}.yaml'
        result[name] = "# Generated by deploy/render.py; edit the Helm chart.\n" + yaml.safe_dump(doc, sort_keys=False)
    chart = yaml.safe_load((ROOT / "charts/clever-csi-driver/Chart.yaml").read_text())
    result["manifest.txt"] = f"# clever-csi-driver {chart['version']}; phase: {phase}\n" + "\n".join(result) + "\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "deploy/rendered")
    parser.add_argument("--cluster-id", default="${OVD_CLUSTER_ID}")
    parser.add_argument("--organisation-id", default="${OVD_CSI_ORGANISATION_ID}")
    parser.add_argument("--axo-url", help="Override controller.axoUrl from chart values")
    parser.add_argument("--image-tag", help="Override image.tag from chart values")
    parser.add_argument("--image-digest", help="Pin an image digest; takes precedence over image.tag")
    args = parser.parse_args()
    settings = {k: getattr(args, k) for k in ["cluster_id", "organisation_id", "axo_url", "image_tag", "image_digest"]}
    failed = False
    for phase in ["stage", "attach", "final"]:
        expected = bundle(phase, **settings)
        destination = args.output / phase
        actual_names = {p.name for p in destination.iterdir()} if destination.exists() else set()
        stale = actual_names - expected.keys()
        if args.check:
            for name, content in expected.items():
                path = destination / name
                actual = path.read_text() if path.exists() else ""
                if actual != content:
                    print("".join(difflib.unified_diff(actual.splitlines(True), content.splitlines(True), fromfile=str(path), tofile="rendered")))
                    failed = True
            if stale:
                print(f"{destination}: stale files {sorted(stale)}")
                failed = True
        else:
            destination.mkdir(parents=True, exist_ok=True)
            for name in stale:
                (destination / name).unlink()
            for name, content in expected.items():
                (destination / name).write_text(content)
    raise SystemExit(1 if failed else 0)


if __name__ == "__main__":
    main()
